import {
  ensureFieldIds,
  removeInheritedFields as removeTrackedInheritedFields,
  syncInheritedFields as syncTrackedInheritedFields,
  persistInheritedFieldIds as persistSourceFieldIds,
  trackInheritedFields,
  newFieldId,
} from '../../../cli/board/field-inheritance.js';

// Fields of Screen, Command, Event and Read Model elements (R9): the data they carry. Fields are
// copied along the arrows, never linked. This file holds the field model and the copy rules
// (no UI). Fields may carry a stable `id` and `inheritedFrom` metadata; object fields have
// nested `fields`.

export const FIELD_KINDS = ['screen', 'command', 'event', 'read_model'];
export const hasFields = (kind) => FIELD_KINDS.includes(kind);

export const OBJECT = 'object';
export const PRIMITIVES = ['string', 'integer', 'decimal', 'boolean', 'date', 'datetime', 'uuid'];
export const FIELD_TYPES = [...PRIMITIVES, OBJECT];

// The true/false attributes of a field, with the tooltip that explains each.
export const FIELD_FLAGS = [
  { key: 'identifier', label: 'Identifier', hint: 'Identifies the object' },
  { key: 'optional', label: 'Optional', hint: 'May be missing' },
  { key: 'generated', label: 'Generated', hint: 'Generated by the system, e.g. an id or the current date' },
  { key: 'pii', label: 'PII', hint: 'Personally identifiable information' },
  { key: 'technical', label: 'Technical', hint: 'An implementation detail, not part of the business model' },
];

export const newField = () => ({
  name: '',
  id: newFieldId(),
  type: 'string',
  list: false,
  ...Object.fromEntries(FIELD_FLAGS.map((f) => [f.key, false])),
});

export const cloneFields = (fields) => structuredClone(fields ?? []);

// Puts `incoming` fields into `own`: a field of the same name is replaced (in place), others
// are appended. Copies, so nothing stays linked.
export function mergeFields(own, incoming) {
  const result = cloneFields(own);
  for (const f of cloneFields(incoming)) {
    const i = result.findIndex((r) => r.name === f.name);
    if (i === -1) result.push(f);
    else result[i] = f;
  }
  return result;
}

const isHolder = (n) => n?.type === 'sticky' && hasFields(n.data.kind);

// The fields an element shows: a linked copy shows its original's (R3.22).
export const fieldsOf = (byId, n) => (n.data.copyOf ? byId.get(n.data.copyOf)?.data.fields : n.data.fields) ?? [];

// The elements with fields that feed element `id`: itself, or, for a Processor (which has no
// fields but passes them on), the ones feeding it.
function sources(byId, edges, id, seen = new Set()) {
  const n = byId.get(id);
  if (!n || seen.has(id)) return [];
  if (n.data?.kind === 'processor') {
    seen.add(id);
    return edges.filter((e) => e.target === id).flatMap((e) => sources(byId, edges, e.source, seen));
  }
  return isHolder(n) ? [n] : [];
}

// The editable elements with fields that element `id` feeds: itself, or, for a Processor, the
// ones it feeds. A linked copy is not editable.
function targets(byId, edges, id, seen = new Set()) {
  const n = byId.get(id);
  if (!n || seen.has(id)) return [];
  if (n.data?.kind === 'processor') {
    seen.add(id);
    return edges.filter((e) => e.source === id).flatMap((e) => targets(byId, edges, e.target, seen));
  }
  return isHolder(n) && !n.data.copyOf ? [n] : [];
}

// Applies { id -> fields } to the nodes; the same array when nothing changes.
function withFields(nodes, changed) {
  if (!changed.size) return nodes;
  return nodes.map((n) => (changed.has(n.id) ? { ...n, data: { ...n.data, fields: changed.get(n.id) } } : n));
}

// Arrows were added (`added`: [source, target] pairs; `edges` holds all arrows, the new
// ones too): every field of the source is copied to the target, replacing fields of the same name.
export function inheritOnConnect(nodes, edges, added) {
  const byId = new Map(nodes.map((n) => [n.id, n]));
  const changed = new Map();
  for (const [s, t] of added) {
    for (const src of sources(byId, edges, s)) {
      const sourceId = src.data.copyOf ?? src.id;
      const fields = ensureFieldIds(fieldsOf(byId, src));
      if (!fields.length) continue;
      changed.set(sourceId, fields);
      for (const dst of targets(byId, edges, t)) {
        if (dst.id === sourceId) continue;
        changed.set(
          dst.id,
          mergeFields(
            changed.get(dst.id) ?? dst.data.fields,
            trackInheritedFields(fields, sourceId)
          )
        );
      }
    }
  }
  return withFields(nodes, changed);
}

// The fields of all the parents of element `id` (the elements with an arrow to it, through
// Processors); a later parent replaces a field of the same name of an earlier one.
export function parentFields(nodes, edges, id) {
  const byId = new Map(nodes.map((n) => [n.id, n]));
  let result = [];
  for (const e of edges.filter((x) => x.target === id)) {
    for (const src of sources(byId, edges, e.source)) {
      if (src.id !== id) {
        const sourceId = src.data.copyOf ?? src.id;
        result = mergeFields(
          result,
          trackInheritedFields(ensureFieldIds(fieldsOf(byId, src)), sourceId)
        );
      }
    }
  }
  return result;
}

export function parentFieldConflicts(nodes, edges, id) {
  const byId = new Map(nodes.map((n) => [n.id, n]));
  const sourcesByName = new Map();
  for (const edge of edges.filter((item) => item.target === id)) {
    for (const source of sources(byId, edges, edge.source)) {
      if (source.id === id) continue;
      const sourceId = source.data.copyOf ?? source.id;
      for (const field of fieldsOf(byId, source)) {
        const contributions = sourcesByName.get(field.name) ?? [];
        if (!contributions.some((item) => item.sourceId === sourceId)) {
          contributions.push({ sourceId, field });
        }
        sourcesByName.set(field.name, contributions);
      }
    }
  }
  return [...sourcesByName]
    .filter(([, contributions]) => contributions.length > 1)
    .map(([name, sources]) => ({
      name,
      sources,
      winnerId: sources[sources.length - 1].sourceId,
    }));
}

// A field holder is incomplete when it has a non-generated top-level field no parent supplies.
export function hasUninheritedFields(nodes, edges, id) {
  const target = nodes.find((n) => n.id === id);
  if (!isHolder(target) || target.data.copyOf) return false;
  const inherited = new Set(parentFields(nodes, edges, id).map((field) => field.name));
  return (target.data.fields ?? []).some((field) => !field.generated && !inherited.has(field.name));
}

export function incompleteFieldTargets(nodes, edges) {
  return new Set([...new Set(edges.map((edge) => edge.target))]
    .filter((id) => hasUninheritedFields(nodes, edges, id)));
}

// Copies `fields` to every element downstream of `fromId` (transitively, around loops too).
export function propagateFields(nodes, edges, fromId, fields) {
  if (!fields.length) return nodes;
  const withIds = ensureFieldIds(fields);
  const sourceElements = nodes
    .filter((n) => n.type === 'sticky' && hasFields(n.data.kind) && !n.data.copyOf)
    .map((n) => ({ id: n.id, fields: n.data.fields ?? [] }));
  const sourceUpdates = persistSourceFieldIds(
    sourceElements,
    trackInheritedFields(withIds, fromId)
  );
  const startingNodes = withFields(nodes, sourceUpdates);
  const byId = new Map(startingNodes.map((n) => [n.id, n]));
  const seen = new Set([fromId]);
  const queue = [fromId];
  const changed = new Map();
  while (queue.length) {
    const id = queue.shift();
    for (const e of edges.filter((x) => x.source === id)) {
      if (seen.has(e.target)) continue;
      seen.add(e.target);
      queue.push(e.target);
      const n = byId.get(e.target);
      if (isHolder(n) && !n.data.copyOf) {
        changed.set(n.id, mergeFields(n.data.fields, trackInheritedFields(withIds, fromId)));
      }
    }
  }
  return withFields(startingNodes, changed);
}

export function persistInheritedFieldIds(nodes, fields) {
  const elements = nodes
    .filter((n) => n.type === 'sticky' && hasFields(n.data.kind) && !n.data.copyOf)
    .map((n) => ({ id: n.id, fields: n.data.fields ?? [] }));
  return withFields(nodes, persistSourceFieldIds(elements, fields));
}

export function syncInheritedFieldChanges(nodes, sourceId, previous, next) {
  const elements = nodes
    .filter((n) => n.type === 'sticky' && hasFields(n.data.kind) && !n.data.copyOf)
    .map((n) => ({ id: n.id, fields: n.data.fields ?? [] }));
  const changed = syncTrackedInheritedFields(elements, sourceId, previous, next);
  return withFields(nodes, changed);
}

export function removeInheritedFieldsFromElements(nodes, elementIds) {
  let updated = nodes;
  for (const id of elementIds) {
    const elements = updated
      .filter((node) => isHolder(node) && !node.data.copyOf)
      .map((node) => ({ id: node.id, fields: node.data.fields ?? [] }));
    updated = withFields(updated, removeTrackedInheritedFields(elements, id));
  }
  return updated;
}

// The export form of a field list: fixed key order, `fields` only for objects (R6.5).
export const serializeFields = (fields) =>
  fields.map((f) => ({
    name: f.name,
    type: f.type,
    list: !!f.list,
    ...(f.id ? { id: f.id } : {}),
    ...Object.fromEntries(FIELD_FLAGS.map(({ key }) => [key, !!f[key]])),
    ...(f.inheritedFrom ? { inheritedFrom: structuredClone(f.inheritedFrom) } : {}),
    ...(f.type === OBJECT ? { fields: serializeFields(f.fields ?? []) } : {}),
  }));
