#!/usr/bin/env node
// Exports the data one context's prototype needs to prototype/model.js (read-only on the board).
// Usage: node export-model.mjs --context <id or name> [--base http://localhost:3300] [--out prototype/model.js]
import fs from 'node:fs';
import path from 'node:path';

const args = Object.fromEntries(
  process.argv.slice(2).reduce((acc, a, i, all) => (a.startsWith('--') ? [...acc, [a.slice(2), all[i + 1]]] : acc), []),
);
if (!args.context) {
  console.error('Usage: node export-model.mjs --context <id or name> [--base URL] [--out prototype/model.js]');
  process.exit(1);
}
const BASE = (args.base ?? 'http://localhost:3300').replace(/\/$/, '') + '/api/model';
const OUT = args.out ?? 'prototype/model.js';
const get = async (p) => {
  const r = await fetch(BASE + p);
  if (!r.ok) throw new Error(`GET ${p} -> ${r.status} ${await r.text()}`);
  return r.json();
};

const contexts = await get('/outline');
const ctx = contexts.filter((c) => c.id === args.context || c.name.toLowerCase() === args.context.toLowerCase());
if (ctx.length !== 1) {
  console.error(ctx.length ? `Several Contexts are named "${args.context}": use the id` : `No Context "${args.context}". Known: ${contexts.map((c) => `${c.name} (${c.id})`).join(', ')}`);
  process.exit(1);
}
const context = ctx[0];

// All Chapters are read: linked copies point to originals in other Chapters (and older models may have arrows across Chapters).
const els = new Map();
const inContext = new Set();
for (const c of contexts) {
  for (const o of c.chapters) {
    const ch = await get(`/chapters/${o.id}`);
    for (const s of ch.slices) for (const e of s.elements) els.set(e.id, { ...e, chapterId: ch.id, chapterName: ch.name, sliceName: s.name });
    if (c.id === context.id) inContext.add(o.id);
  }
}
const orig = (e) => (e.copyOf ? els.get(e.copyOf) ?? e : e);
const mine = [...els.values()].filter((e) => inContext.has(e.chapterId));
const parentsOf = (id) => [...els.values()].filter((e) => (e.connectsTo ?? []).includes(id));
const childrenOf = (e) => (e.connectsTo ?? []).map((t) => els.get(t)).filter(Boolean);
const uniq = (xs) => [...new Set(xs)];
const ids = (xs) => uniq(xs.map((e) => orig(e).id));

const model = { context: { id: context.id, name: context.name }, screens: [], commands: [], events: [], readModels: [], processors: [], scenarios: [] };
const seen = new Set();
for (const e0 of mine) {
  const e = orig(e0);
  if (seen.has(e.id)) continue;
  seen.add(e.id);
  const copies = [e, ...[...els.values()].filter((x) => x.copyOf === e.id)];
  const kids = copies.flatMap(childrenOf);
  const pars = copies.flatMap((c) => parentsOf(c.id));
  const base = { id: e.id, name: e.name ?? '', chapter: e.chapterName, slice: e.sliceName };
  if (e.type === 'SCREEN') {
    model.screens.push({ ...base, html: e.html ?? null, url: e.url ?? null, fields: e.fields ?? [], commandIds: ids(kids.filter((k) => k.type === 'COMMAND')), readModelIds: ids(pars.filter((p) => p.type === 'READ_MODEL')) });
  } else if (e.type === 'COMMAND') {
    model.commands.push({ ...base, fields: e.fields ?? [], screenIds: ids(pars.filter((p) => p.type === 'SCREEN')), processorIds: ids(pars.filter((p) => p.type === 'PROCESSOR')), eventIds: ids(kids.filter((k) => k.type === 'EVENT')) });
  } else if (e.type === 'EVENT') {
    model.events.push({ ...base, fields: e.fields ?? [] });
  } else if (e.type === 'READ_MODEL') {
    model.readModels.push({ ...base, fields: e.fields ?? [], eventIds: ids(pars.filter((p) => p.type === 'EVENT')), processorIds: ids(kids.filter((k) => k.type === 'PROCESSOR')), screenIds: ids(kids.filter((k) => k.type === 'SCREEN')) });
  } else if (e.type === 'PROCESSOR') {
    model.processors.push({ ...base, readModelIds: ids(pars.filter((p) => p.type === 'READ_MODEL')), commandIds: ids(kids.filter((k) => k.type === 'COMMAND')) });
  } else if (e.type === 'SCENARIOS') {
    for (const s of e.scenarios ?? []) model.scenarios.push({ id: s.id, name: s.name, description: s.description, chapter: e.chapterName, given: s.given, when: s.when, then: s.then, error: s.error });
  }
}

// An Event closes a todo-list item of a Read Model when one of its Processors' Commands produces it.
for (const q of model.readModels) {
  const cmds = q.processorIds.flatMap((p) => model.processors.find((x) => x.id === p)?.commandIds ?? []);
  q.closingEventIds = uniq(cmds.flatMap((c) => model.commands.find((x) => x.id === c)?.eventIds ?? []));
  q.openingEventIds = q.eventIds.filter((id) => !q.closingEventIds.includes(id));
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, `// Generated by export-model.mjs: do not edit.\nconst MODEL = ${JSON.stringify(model)};\n`);
const n = (k) => model[k].length;
for (const q of model.readModels) {
  const loose = q.closingEventIds.filter((id) => !q.eventIds.includes(id));
  if (loose.length) console.warn(`Warning: Read Model "${q.name}": the Event(s) ${loose.map((id) => `"${model.events.find((e) => e.id === id)?.name}"`).join(', ')} close its todo list but have no arrow to it, so items never close`);
}
console.log(`Wrote ${OUT}: ${n('screens')} screens (${model.screens.filter((s) => !s.html && !s.url).length} without mockup), ${n('commands')} commands, ${n('events')} events, ${n('readModels')} read models, ${n('processors')} processors, ${n('scenarios')} scenarios`);
