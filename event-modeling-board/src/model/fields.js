// Fields of Screen, Command, Event and Query elements (R9): the data they carry. Fields are
// copied along the arrows, never linked. This file holds the field model and the copy rules
// (no UI). A field is { name, type, list, id, optional, generated, pii, technical } plus
// `fields` (its own fields) when its type is 'object'.

export const FIELD_KINDS = ['screen', 'command', 'event', 'query'];
export const hasFields = (kind) => FIELD_KINDS.includes(kind);

export const OBJECT = 'object';
export const PRIMITIVES = ['string', 'integer', 'decimal', 'boolean', 'date', 'datetime', 'uuid'];
export const FIELD_TYPES = [...PRIMITIVES, OBJECT];

// The true/false attributes of a field, with the tooltip that explains each.
export const FIELD_FLAGS = [
  { key: 'id', label: 'ID', hint: 'Identifies the object' },
  { key: 'optional', label: 'Optional', hint: 'May be missing' },
  { key: 'generated', label: 'Generated', hint: 'Generated by the system, e.g. an id or the current date' },
  { key: 'pii', label: 'PII', hint: 'Personally identifiable information' },
  { key: 'technical', label: 'Technical', hint: 'An implementation detail, not part of the business model' },
];

export const newField = () => ({
  name: '',
  type: 'string',
  list: false,
  ...Object.fromEntries(FIELD_FLAGS.map((f) => [f.key, false])),
});

export const cloneFields = (fields) => structuredClone(fields ?? []);

// Puts `incoming` fields into `own`: a field of the same name is replaced (in place), others
// are appended. Copies, so nothing stays linked.
export function mergeFields(own, incoming) {
  const result = cloneFields(own);
  for (const f of cloneFields(incoming)) {
    const i = result.findIndex((r) => r.name === f.name);
    if (i === -1) result.push(f);
    else result[i] = f;
  }
  return result;
}

const isHolder = (n) => n?.type === 'sticky' && hasFields(n.data.kind);

// The fields an element shows: a linked copy shows its original's (R3.22).
export const fieldsOf = (byId, n) => (n.data.copyOf ? byId.get(n.data.copyOf)?.data.fields : n.data.fields) ?? [];

// The elements with fields that feed element `id`: itself, or, for a Processor (which has no
// fields but passes them on), the ones feeding it.
function sources(byId, edges, id, seen = new Set()) {
  const n = byId.get(id);
  if (!n || seen.has(id)) return [];
  if (n.data?.kind === 'processor') {
    seen.add(id);
    return edges.filter((e) => e.target === id).flatMap((e) => sources(byId, edges, e.source, seen));
  }
  return isHolder(n) ? [n] : [];
}

// The editable elements with fields that element `id` feeds: itself, or, for a Processor, the
// ones it feeds. A linked copy is not editable.
function targets(byId, edges, id, seen = new Set()) {
  const n = byId.get(id);
  if (!n || seen.has(id)) return [];
  if (n.data?.kind === 'processor') {
    seen.add(id);
    return edges.filter((e) => e.source === id).flatMap((e) => targets(byId, edges, e.target, seen));
  }
  return isHolder(n) && !n.data.copyOf ? [n] : [];
}

// Applies { id -> fields } to the nodes; the same array when nothing changes.
function withFields(nodes, changed) {
  if (!changed.size) return nodes;
  return nodes.map((n) => (changed.has(n.id) ? { ...n, data: { ...n.data, fields: changed.get(n.id) } } : n));
}

// Arrows were added (`added`: [source, target] pairs; `edges` holds all arrows, the new
// ones too): every field of the source is copied to the target, replacing fields of the same name.
export function inheritOnConnect(nodes, edges, added) {
  const byId = new Map(nodes.map((n) => [n.id, n]));
  const changed = new Map();
  for (const [s, t] of added) {
    for (const src of sources(byId, edges, s)) {
      const fields = fieldsOf(byId, src);
      if (!fields.length) continue;
      for (const dst of targets(byId, edges, t)) {
        if (dst.id === src.id) continue;
        changed.set(dst.id, mergeFields(changed.get(dst.id) ?? dst.data.fields, fields));
      }
    }
  }
  return withFields(nodes, changed);
}

// The fields of all the parents of element `id` (the elements with an arrow to it, through
// Processors); a later parent replaces a field of the same name of an earlier one.
export function parentFields(nodes, edges, id) {
  const byId = new Map(nodes.map((n) => [n.id, n]));
  let result = [];
  for (const e of edges.filter((x) => x.target === id)) {
    for (const src of sources(byId, edges, e.source)) {
      if (src.id !== id) result = mergeFields(result, fieldsOf(byId, src));
    }
  }
  return result;
}

// Copies `fields` to every element downstream of `fromId` (transitively, around loops too).
export function propagateFields(nodes, edges, fromId, fields) {
  if (!fields.length) return nodes;
  const byId = new Map(nodes.map((n) => [n.id, n]));
  const seen = new Set([fromId]);
  const queue = [fromId];
  const changed = new Map();
  while (queue.length) {
    const id = queue.shift();
    for (const e of edges.filter((x) => x.source === id)) {
      if (seen.has(e.target)) continue;
      seen.add(e.target);
      queue.push(e.target);
      const n = byId.get(e.target);
      if (isHolder(n) && !n.data.copyOf) changed.set(n.id, mergeFields(n.data.fields, fields));
    }
  }
  return withFields(nodes, changed);
}

// The export form of a field list: fixed key order, `fields` only for objects (R6.5).
export const serializeFields = (fields) =>
  fields.map((f) => ({
    name: f.name,
    type: f.type,
    list: !!f.list,
    ...Object.fromEntries(FIELD_FLAGS.map(({ key }) => [key, !!f[key]])),
    ...(f.type === OBJECT ? { fields: serializeFields(f.fields ?? []) } : {}),
  }));
